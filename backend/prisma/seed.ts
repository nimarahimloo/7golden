// Persian price formatter: 1234567 -> "۱٬۲۳۴٬۵۶۷"
function faPrice(n: number): string {
  const faDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return n
    .toLocaleString('en-US')
    .replace(/[0-9]/g, (d) => faDigits[+d]);
}

